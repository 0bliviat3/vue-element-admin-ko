<template>
  <div class="login-container">
    <el-form
      ref="loginForm"
      :model="loginForm"
      :rules="loginRules"
      class="login-form"
      autocomplete="on"
      label-position="left"
    >
      <div class="title-container">
        <h3 class="title">로그인</h3>
      </div>

      <!-- 아이디 입력 -->
      <el-form-item prop="username">
        <span class="svg-container">
          <svg-icon icon-class="user" />
        </span>
        <el-input
          ref="username"
          v-model="loginForm.userId"
          placeholder="아이디"
          name="userId"
          type="text"
          tabindex="1"
          autocomplete="on"
        />
      </el-form-item>

      <!-- 비밀번호 입력 -->
      <el-tooltip v-model="capsTooltip" content="Caps lock이 켜져 있습니다" placement="right" manual>
        <el-form-item prop="password">
          <span class="svg-container">
            <svg-icon icon-class="password" />
          </span>
          <el-input
            :key="passwordType"
            ref="password"
            v-model="loginForm.password"
            :type="passwordType"
            placeholder="비밀번호"
            name="password"
            tabindex="2"
            autocomplete="on"
            @keyup.native="checkCapslock"
            @blur="capsTooltip = false"
            @keyup.enter.native="handleLogin"
          />
          <span class="show-pwd" @click="showPwd">
            <svg-icon :icon-class="passwordType === 'password' ? 'eye' : 'eye-open'" />
          </span>
        </el-form-item>
      </el-tooltip>

      <!-- 로그인 버튼 -->
      <el-button
        :loading="loading"
        type="primary"
        style="width:100%;margin-bottom:30px;"
        @click.native.prevent="handleLogin"
      >
        로그인
      </el-button>

      <!-- 회원가입 버튼 -->
      <div style="text-align:center;">
        <span style="color:#fff; margin-right:10px;">아직 계정이 없으신가요?</span>
        <el-button
          class="signup-button"
          type="success"
          size="mini"
          @click="$router.push('/register')"
        >
          회원가입
        </el-button>
      </div>
    </el-form>
  </div>
</template>

<script>

export default {
  name: 'Login',
  data() {
    const validateUsername = (rule, value, callback) => {
      if (!value) {
        callback(new Error('아이디를 입력해주세요'))
      } else {
        callback()
      }
    }
    const validatePassword = (rule, value, callback) => {
      if (!value || value.length < 6) {
        callback(new Error('비밀번호는 6자 이상이어야 합니다'))
      } else {
        callback()
      }
    }
    return {
      loginForm: {
        userId: '',
        password: ''
      },
      loginRules: {
        userId: [{ required: true, trigger: 'blur', validator: validateUsername }],
        password: [{ required: true, trigger: 'blur', validator: validatePassword }]
      },
      passwordType: 'password',
      capsTooltip: false,
      loading: false
    }
  },
  methods: {
    checkCapslock(e) {
      const { key } = e
      this.capsTooltip = key && key.length === 1 && key >= 'A' && key <= 'Z'
    },
    showPwd() {
      this.passwordType = this.passwordType === 'password' ? '' : 'password'
      this.$nextTick(() => {
        this.$refs.password.focus()
      })
    },
    async handleLogin() {
      this.$refs.loginForm.validate(async(valid) => {
        if (!valid) return
        this.loading = true
        try {
          await this.$store.dispatch('user/login', {
            userId: this.loginForm.userId,
            password: this.loginForm.password
          })
          this.$router.push({ path: this.redirect || '/', query: this.otherQuery })
        } catch (err) {
          console.error(err)
          this.$message.error('아이디 또는 비밀번호를 확인해주세요')
        } finally {
          this.loading = false
        }
      })
    }
  }
}
</script>

